"""Render playbooks as Markdown checklists and a full project worksheet."""
from __future__ import annotations

from io import StringIO

from .loader import Playbook, PlaybookItem, list_playbooks

TYPES_BOX: dict[str, str] = {
    "question": "[ ] Q",
    "task": "[ ] T",
    "decision": "[ ] D",
    "evidence": "[ ] E",
    "owners": "[ ] O",
}


def _render_item(item: PlaybookItem) -> str:
    """One playbook item as a checkbox line with type and owner."""
    box = TYPES_BOX.get(item.type, "[ ] ?")
    head = f"- {box} **{item.title}** "
    if item.default_owner:
        head += f"_(owner: {item.default_owner})_"
    head += "  \n  "
    head += item.description.strip()
    if item.example_response:
        head += f"\n  > Example:\n  >\n  > ```\n  > {item.example_response.strip()}\n  > ```"
    if item.see_also:
        head += "\n  > See also: " + ", ".join(s for s in item.see_also)
    return head


def render_playbook(playbook: Playbook, project_name: str = "<engagement>") -> str:
    """Render one playbook as a Markdown checklist for `project_name`."""
    out = StringIO()
    out.write(f"# {playbook.title}: {project_name}\n\n")
    out.write(f"**Phase:** `{playbook.phase}` · **Items:** {len(playbook.items)}\n\n")
    out.write(playbook.purpose.strip() + "\n\n")
    if playbook.see_also:
        out.write("**See also:**\n\n")
        for ref in playbook.see_also:
            out.write(f"- {ref}\n")
        out.write("\n")
    out.write("## Checklist\n\n")
    for item in playbook.items:
        out.write(_render_item(item) + "\n\n")
    return out.getvalue()


def render_project(project_name: str, root=None) -> str:
    """Render the full project worksheet (all five phases) for one engagement."""
    out = StringIO()
    out.write(f"# {project_name}: Forward Deployed Engineering worksheet\n\n")
    out.write(
        "Generated by `fde-portfolio` from the bundled playbook data. "
        "Each phase is validated against the JSON Schema in "
        "`src/fde_portfolio/schemas/`; the rendered items are the source "
        "of truth for the checklist, not the prose.\n\n"
    )
    out.write("## Phases\n\n")
    for playbook in list_playbooks(root=root):
        out.write(f"- **{playbook.title}** ({len(playbook.items)} items)\n")
    out.write("\n---\n\n")
    for playbook in list_playbooks(root=root):
        out.write(render_playbook(playbook, project_name=project_name))
        out.write("---\n\n")
    return out.getvalue()
